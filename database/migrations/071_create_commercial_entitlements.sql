with legacy_summary as (
  select
    f.tenant_id,
    jsonb_agg(jsonb_build_object(
      'feature_id',f.id,'subscription_type',f.subscription_type,'plan',f.plan,
      'builder_type',f.builder_type,'payment_status',f.payment_status,
      'updated_at',f.updated_at
    ) order by f.updated_at desc, f.id desc) as legacy_records,
    count(*) filter (where lower(trim(f.payment_status))='active') as active_count,
    min(f.id) filter (where lower(trim(f.payment_status))='active') as single_active_id
  from public.features f
  group by f.tenant_id
),
active_record as (
  select
    summary.tenant_id,
    summary.legacy_records,
    summary.active_count,
    case when summary.active_count=1 then active_feature.id else null end as active_feature_id,
    case when summary.active_count=1 then jsonb_build_object(
      'feature_id',active_feature.id,
      'subscription_type',active_feature.subscription_type,
      'plan',active_feature.plan,
      'builder_type',active_feature.builder_type,
      'payment_status',active_feature.payment_status,
      'updated_at',active_feature.updated_at
    ) else null end as active_feature,
    case
      when summary.active_count<>1 then null
      when lower(trim(active_feature.plan))='complete' then 'business_plus'
      when lower(trim(active_feature.plan))='cms_plus' then 'business'
      when lower(trim(active_feature.plan))='cms' then 'website'
      when lower(trim(active_feature.plan))='forms_data' then 'forms'
      when lower(trim(active_feature.subscription_type))='individual_builder'
        and lower(trim(coalesce(active_feature.builder_type,'')))='reservation'
        then 'business_plus'
      when lower(trim(active_feature.subscription_type))='individual_builder'
        and lower(trim(coalesce(active_feature.builder_type,'')))='website'
        then 'website'
      when lower(trim(active_feature.subscription_type))='individual_builder'
        and lower(trim(coalesce(active_feature.builder_type,''))) in ('forms','data')
        then 'forms'
      else null
    end as recommended_plan_id
  from legacy_summary summary
  left join public.features active_feature
    on active_feature.id=summary.single_active_id
    and summary.active_count=1
)
