create or replace function public.increment_commercial_usage(
  p_tenant_id integer,
  p_period_key text,
  p_metric text,
  p_delta integer default 1
) returns table (
  forms_created bigint,
  form_submissions bigint,
  reservation_requests bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_delta integer := greatest(coalesce(p_delta, 0), 0);
begin
  if p_metric not in ('forms_created','form_submissions','reservation_requests') then
    raise exception using errcode='P0001', message='commercial_usage_metric_invalid';
  end if;

  insert into public.commercial_usage_monthly (tenant_id, period_key)
  values (p_tenant_id, p_period_key)
  on conflict (tenant_id, period_key) do nothing;

  if p_metric = 'forms_created' then
    update public.commercial_usage_monthly set forms_created = forms_created + v_delta, updated_at = now()
    where tenant_id = p_tenant_id and period_key = p_period_key;
  elsif p_metric = 'form_submissions' then
    update public.commercial_usage_monthly set form_submissions = form_submissions + v_delta, updated_at = now()
    where tenant_id = p_tenant_id and period_key = p_period_key;
  else
    update public.commercial_usage_monthly set reservation_requests = reservation_requests + v_delta, updated_at = now()
    where tenant_id = p_tenant_id and period_key = p_period_key;
  end if;

  return query select u.forms_created, u.form_submissions, u.reservation_requests
  from public.commercial_usage_monthly u
  where u.tenant_id = p_tenant_id and u.period_key = p_period_key;
end;
$$;

create or replace function public.ensure_ai_monthly_allocation(
  p_tenant_id integer,
  p_period_key text,
  p_product_id text,
  p_standard_tokens bigint,
  p_idempotency_key text,
  p_reason text
) returns setof public.ai_token_allocations
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.ai_token_allocations%rowtype;
  v_created public.ai_token_allocations%rowtype;
begin
  if p_product_id not in ('ai_analytics_starter','ai_analytics_plus')
    or p_standard_tokens <= 0
    or p_period_key !~ '^[0-9]{4}-[0-9]{2}$'
  then
    raise exception using errcode='P0001',message='ai_monthly_allocation_invalid';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(p_tenant_id::text || ':' || p_period_key,0)
  );
  if not exists (
    select 1
    from public.tenant_addons addon
    where addon.tenant_id=p_tenant_id
      and addon.addon_id=p_product_id
      and addon.state='active'
      and addon.billing_interval='month'
  ) then
    raise exception using errcode='P0001',message='ai_monthly_package_not_active';
  end if;
  select * into v_existing
  from public.ai_token_allocations
  where tenant_id=p_tenant_id and idempotency_key=p_idempotency_key
  limit 1;
  if found then
    if v_existing.product_id<>p_product_id
      or v_existing.period_key<>p_period_key
      or v_existing.standard_tokens<>p_standard_tokens
      or v_existing.allocation_type<>'monthly_package'
    then
      raise exception using errcode='P0001',message='ai_monthly_allocation_idempotency_conflict';
    end if;
    if v_existing.state<>'active' then
      update public.ai_token_allocations
      set state='revoked'
      where tenant_id=p_tenant_id
        and period_key=p_period_key
        and allocation_type='monthly_package'
        and state='active'
        and id<>v_existing.id;
      update public.ai_token_allocations
      set state='active'
      where id=v_existing.id
      returning * into v_existing;
    end if;
    return next v_existing;
    return;
  end if;

  update public.ai_token_allocations
  set state='revoked'
  where tenant_id=p_tenant_id
    and period_key=p_period_key
    and allocation_type='monthly_package'
    and state='active';

  insert into public.ai_token_allocations (
    tenant_id,period_key,allocation_type,product_id,standard_tokens,state,
    idempotency_key,reason
  ) values (
    p_tenant_id,p_period_key,'monthly_package',p_product_id,p_standard_tokens,
    'active',p_idempotency_key,p_reason
  ) returning * into v_created;
  return next v_created;
end;
$$;

create or replace function public.reserve_ai_standard_tokens(
  p_tenant_id integer,
  p_user_id integer,
  p_period_key text,
  p_request_id text,
  p_operation_type text,
  p_reserved_tokens bigint,
  p_expires_at timestamptz
) returns table (
  accepted boolean,
  request_id text,
  allocated_tokens bigint,
  used_tokens bigint,
  reserved_tokens bigint,
  remaining_tokens bigint,
  reservation_status text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_allocated bigint;
  v_used bigint;
  v_reserved bigint;
  v_existing public.ai_token_reservations%rowtype;
begin
  if p_reserved_tokens <= 0
    or length(trim(p_request_id)) < 8
    or p_expires_at <= now()
    or p_expires_at > now() + interval '1 hour'
  then
    raise exception using errcode='P0001', message='ai_token_reservation_invalid';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text || ':' || p_period_key, 0));

  select * into v_existing from public.ai_token_reservations where ai_token_reservations.request_id = p_request_id;
  if found then
    if v_existing.tenant_id <> p_tenant_id or v_existing.user_id <> p_user_id
      or v_existing.period_key <> p_period_key or v_existing.operation_type <> p_operation_type then
      raise exception using errcode='P0001', message='ai_token_idempotency_conflict';
    end if;
    if v_existing.status='reserved' and v_existing.expires_at <= now() then
      update public.ai_token_reservations
      set status='expired'
      where ai_token_reservations.request_id=p_request_id
        and status='reserved';
      v_existing.status := 'expired';
    end if;
    select coalesce(sum(standard_tokens),0) into v_allocated
      from public.ai_token_allocations where tenant_id=p_tenant_id and period_key=p_period_key and state='active';
    select coalesce(sum(standard_tokens),0) into v_used
      from public.ai_token_ledger where tenant_id=p_tenant_id and period_key=p_period_key;
    select coalesce(sum(reserved_standard_tokens),0) into v_reserved
      from public.ai_token_reservations
      where tenant_id=p_tenant_id and period_key=p_period_key and status='reserved' and expires_at > now();
    return query select (
        v_existing.status = 'reserved' and v_existing.expires_at > now()
      ), v_existing.request_id,
      v_allocated, v_used, v_reserved, greatest(v_allocated-v_used-v_reserved,0),
      v_existing.status;
    return;
  end if;

  update public.ai_token_reservations set status='expired'
  where tenant_id=p_tenant_id and period_key=p_period_key and status='reserved' and expires_at <= now();

  select coalesce(sum(standard_tokens),0) into v_allocated
    from public.ai_token_allocations where tenant_id=p_tenant_id and period_key=p_period_key and state='active';
  select coalesce(sum(standard_tokens),0) into v_used
    from public.ai_token_ledger where tenant_id=p_tenant_id and period_key=p_period_key;
  select coalesce(sum(reserved_standard_tokens),0) into v_reserved
    from public.ai_token_reservations
    where tenant_id=p_tenant_id and period_key=p_period_key and status='reserved' and expires_at > now();

  if v_allocated-v_used-v_reserved < p_reserved_tokens then
    return query select false, p_request_id, v_allocated, v_used, v_reserved,
      greatest(v_allocated-v_used-v_reserved,0), 'rejected'::text;
    return;
  end if;

  insert into public.ai_token_reservations (
    request_id,tenant_id,user_id,period_key,operation_type,reserved_standard_tokens,expires_at
  ) values (
    p_request_id,p_tenant_id,p_user_id,p_period_key,p_operation_type,p_reserved_tokens,p_expires_at
  );
  v_reserved := v_reserved + p_reserved_tokens;
  return query select true,p_request_id,v_allocated,v_used,v_reserved,
    greatest(v_allocated-v_used-v_reserved,0),'reserved'::text;
end;
$$;

create or replace function public.finalize_ai_standard_tokens(
  p_request_id text,
  p_provider text,
  p_model text,
  p_multiplier_version text,
  p_input_tokens bigint,
  p_cached_input_tokens bigint,
  p_output_tokens bigint,
  p_total_provider_tokens bigint,
  p_standard_tokens bigint,
  p_request_status text,
  p_usage_source text,
  p_estimated boolean
) returns table (
  standard_tokens bigint,
  covered_standard_tokens bigint,
  reservation_applied_tokens bigint,
  additional_applied_tokens bigint,
  deficit_standard_tokens bigint,
  remaining_tokens bigint,
  reservation_status text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reservation public.ai_token_reservations%rowtype;
  v_existing public.ai_token_ledger%rowtype;
  v_allocated bigint;
  v_used bigint;
  v_other_reserved bigint;
  v_available_for_request bigint;
  v_covered bigint;
  v_reservation_applied bigint;
  v_additional_applied bigint;
  v_deficit bigint;
begin
  -- Read the tenant/period before locking, then use the same namespace as
  -- reservation. Re-read the row FOR UPDATE after the advisory lock so reserve
  -- and finalize operations cannot overspend concurrently or deadlock.
  select * into v_reservation
  from public.ai_token_reservations
  where request_id=p_request_id;
  if not found then raise exception using errcode='P0001', message='ai_token_reservation_missing'; end if;

  perform pg_advisory_xact_lock(
    hashtextextended(v_reservation.tenant_id::text || ':' || v_reservation.period_key, 0)
  );
  select * into v_reservation
  from public.ai_token_reservations
  where request_id=p_request_id
  for update;

  select * into v_existing
  from public.ai_token_ledger
  where request_id=p_request_id;
  if found then
    return query select
      v_existing.standard_tokens,
      v_existing.covered_standard_tokens,
      v_existing.reservation_applied_tokens,
      v_existing.additional_applied_tokens,
      v_existing.deficit_standard_tokens,
      greatest((
        select coalesce(sum(allocation.standard_tokens),0)
        from public.ai_token_allocations allocation
        where allocation.tenant_id=v_existing.tenant_id
          and allocation.period_key=v_existing.period_key
          and allocation.state='active'
      ) - (
        select coalesce(sum(ledger.standard_tokens),0)
        from public.ai_token_ledger ledger
        where ledger.tenant_id=v_existing.tenant_id
          and ledger.period_key=v_existing.period_key
      ) - (
        select coalesce(sum(reservation.reserved_standard_tokens),0)
        from public.ai_token_reservations reservation
        where reservation.tenant_id=v_existing.tenant_id
          and reservation.period_key=v_existing.period_key
          and reservation.status='reserved'
          and reservation.expires_at > now()
      ),0)::bigint,
      'finalized'::text;
    return;
  end if;

  -- Finalization is service-role-only and may record a provider call after an
  -- expiry or explicit release. This preserves incurred usage; it does not
  -- restore or create spendable capacity.
  if v_reservation.status not in ('reserved','released','expired') then
    raise exception using errcode='P0001', message='ai_token_reservation_not_finalizable';
  end if;
  if least(p_input_tokens,p_cached_input_tokens,p_output_tokens,p_total_provider_tokens,p_standard_tokens) < 0 then
    raise exception using errcode='P0001', message='ai_token_finalization_invalid';
  end if;

  update public.ai_token_reservations
  set status='expired'
  where tenant_id=v_reservation.tenant_id
    and period_key=v_reservation.period_key
    and request_id<>p_request_id
    and status='reserved'
    and expires_at <= now();

  select coalesce(sum(allocation.standard_tokens),0) into v_allocated
  from public.ai_token_allocations allocation
  where allocation.tenant_id=v_reservation.tenant_id
    and allocation.period_key=v_reservation.period_key
    and allocation.state='active';

  select coalesce(sum(ledger.standard_tokens),0) into v_used
  from public.ai_token_ledger ledger
  where ledger.tenant_id=v_reservation.tenant_id
    and ledger.period_key=v_reservation.period_key;

  select coalesce(sum(reservation.reserved_standard_tokens),0) into v_other_reserved
  from public.ai_token_reservations reservation
  where reservation.tenant_id=v_reservation.tenant_id
    and reservation.period_key=v_reservation.period_key
    and reservation.request_id<>p_request_id
    and reservation.status='reserved'
    and reservation.expires_at > now();

  v_available_for_request := greatest(v_allocated-v_used-v_other_reserved,0);
  v_covered := least(p_standard_tokens,v_available_for_request);
  v_reservation_applied := least(
    v_covered,
    v_reservation.reserved_standard_tokens
  );
  v_additional_applied := greatest(v_covered-v_reservation_applied,0);
  v_deficit := greatest(p_standard_tokens-v_covered,0);

  insert into public.ai_token_ledger (
    request_id,tenant_id,user_id,period_key,provider,model,multiplier_version,
    input_tokens,cached_input_tokens,output_tokens,total_provider_tokens,standard_tokens,
    covered_standard_tokens,reservation_applied_tokens,additional_applied_tokens,
    deficit_standard_tokens,
    operation_type,request_status,usage_source,estimated
  ) values (
    p_request_id,v_reservation.tenant_id,v_reservation.user_id,v_reservation.period_key,
    p_provider,p_model,p_multiplier_version,p_input_tokens,p_cached_input_tokens,p_output_tokens,
    p_total_provider_tokens,p_standard_tokens,v_covered,v_reservation_applied,
    v_additional_applied,v_deficit,v_reservation.operation_type,p_request_status,
    p_usage_source,p_estimated
  );

  update public.ai_token_reservations
  set status='finalized',finalized_standard_tokens=p_standard_tokens,finalized_at=now()
  where request_id=p_request_id;

  return query select
    p_standard_tokens,
    v_covered,
    v_reservation_applied,
    v_additional_applied,
    v_deficit,
    greatest(v_allocated-v_used-v_covered-v_other_reserved,0),
    'finalized'::text;
end;
$$;

create or replace function public.release_ai_standard_tokens(p_request_id text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reservation public.ai_token_reservations%rowtype;
begin
  select * into v_reservation
  from public.ai_token_reservations
  where request_id=p_request_id;
  if not found then return false; end if;
  perform pg_advisory_xact_lock(
    hashtextextended(v_reservation.tenant_id::text || ':' || v_reservation.period_key, 0)
  );
  update public.ai_token_reservations set status='released',finalized_at=now()
  where request_id=p_request_id and status='reserved';
  return found;
end;
$$;

create or replace function public.assign_commercial_subscription(
  p_tenant_id integer,
  p_plan_id text,
  p_state text,
  p_catalog_version text,
  p_price_minor integer,
  p_admin_user_id integer,
  p_reason text,
  p_idempotency_key text
) returns setof public.tenant_subscriptions
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.tenant_subscriptions%rowtype;
  v_created public.tenant_subscriptions%rowtype;
begin
  perform pg_advisory_xact_lock(hashtextextended('commercial-plan:' || p_tenant_id::text, 0));
  select * into v_existing from public.tenant_subscriptions
  where tenant_id=p_tenant_id
    and migration_provenance->>'idempotency_key'=p_idempotency_key
  limit 1;
  if found then return next v_existing; return; end if;

  if p_state='active' then
    update public.tenant_subscriptions
    set state='scheduled_change',updated_at=now(),
      migration_provenance=migration_provenance || jsonb_build_object('replaced_by',p_idempotency_key)
    where tenant_id=p_tenant_id and state='active';
  end if;

  insert into public.tenant_subscriptions (
    tenant_id,plan_id,state,catalog_version,currency,price_minor,billing_interval,
