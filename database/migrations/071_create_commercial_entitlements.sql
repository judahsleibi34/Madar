create or replace function public.normalize_website_standard_path_slug(
  p_value text,
  p_tenant_id integer
) returns text
language plpgsql
immutable
set search_path = public
as $$
declare
  v_slug text;
begin
  v_slug := lower(trim(coalesce(p_value, '')));
  v_slug := regexp_replace(v_slug, '[^a-z0-9]+', '-', 'g');
  v_slug := trim(both '-' from v_slug);
  v_slug := left(v_slug, 63);
  v_slug := trim(both '-' from v_slug);

  if v_slug = '' or v_slug in (
    'api','admin','auth','billing','dashboard','forms','health','login','logout',
    'pricing','privacy-policy','public','signup','site','static',
    'terms-and-conditions','www'
  ) then
    v_slug := 'site-' || p_tenant_id::text;
  end if;

  return v_slug;
end;
$$;

-- Build all assignments before touching the table. This avoids transient
-- uniqueness failures and makes collision resolution stable by tenant id.
create temporary table website_standard_path_slug_map (
  website_settings_id integer primary key,
  tenant_id integer not null,
  original_subdomain text,
  original_standard_path_slug text,
  normalized_standard_path_slug text not null unique,
  material_change boolean not null,
  collision_resolved boolean not null
) on commit drop;

do $$
declare
  settings_row record;
  v_source text;
  v_base text;
  v_candidate text;
  v_suffix text;
  v_collision_index integer;
  v_force_suffix boolean;
  v_had_collision boolean;
begin
  for settings_row in
    select id, tenant_id, subdomain, standard_path_slug
    from public.website_settings
    order by tenant_id, id
  loop
    v_source := coalesce(
      nullif(trim(settings_row.standard_path_slug), ''),
      nullif(trim(settings_row.subdomain), ''),
      ''
    );
    v_base := public.normalize_website_standard_path_slug(
      v_source,
      settings_row.tenant_id
    );
    v_candidate := v_base;
    v_force_suffix := false;
    v_had_collision := false;
    v_collision_index := 0;

    -- A legacy identifier must not take another tenant's deterministic
    -- site-<tenant_id> fallback, even if that fallback row is processed later.
    if v_candidate ~ '^site-[0-9]+$'
      and v_candidate <> 'site-' || settings_row.tenant_id::text
      and exists (
        select 1
        from public.website_settings fallback_owner
        where 'site-' || fallback_owner.tenant_id::text = v_candidate
      )
    then
      v_force_suffix := true;
    end if;

    while v_force_suffix or exists (
      select 1
      from website_standard_path_slug_map assigned
      where lower(assigned.normalized_standard_path_slug) = lower(v_candidate)
    ) loop
      v_had_collision := true;
      v_force_suffix := false;
      v_collision_index := v_collision_index + 1;
      v_suffix := '-' || settings_row.tenant_id::text
        || case when v_collision_index > 1 then '-' || v_collision_index::text else '' end;
      v_candidate := trim(both '-' from left(v_base, 63 - length(v_suffix))) || v_suffix;
    end loop;

    insert into website_standard_path_slug_map (
      website_settings_id,
      tenant_id,
      original_subdomain,
      original_standard_path_slug,
      normalized_standard_path_slug,
      material_change,
      collision_resolved
    ) values (
      settings_row.id,
      settings_row.tenant_id,
      settings_row.subdomain,
      settings_row.standard_path_slug,
      v_candidate,
      v_candidate is distinct from nullif(lower(trim(v_source)), ''),
      v_had_collision
    );
  end loop;
end
$$;

