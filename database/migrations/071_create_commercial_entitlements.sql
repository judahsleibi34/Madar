  ) values (
    p_tenant_id,p_plan_id,p_state,p_catalog_version,'USD',p_price_minor,'month',
    'admin',p_admin_user_id,jsonb_build_object(
      'idempotency_key',p_idempotency_key,'reason',p_reason,'assigned_at',now()
    ),now()
  ) returning * into v_created;
  return next v_created;
end;
$$;

create or replace function public.assign_commercial_addon(
  p_tenant_id integer,
  p_addon_id text,
  p_quantity integer,
  p_state text,
  p_catalog_version text,
  p_price_minor integer,
  p_billing_interval text,
  p_admin_user_id integer,
  p_reason text,
  p_idempotency_key text
) returns setof public.tenant_addons
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.tenant_addons%rowtype;
  v_created public.tenant_addons%rowtype;
  v_lock_group text;
begin
  v_lock_group := case
    when p_addon_id in ('ai_analytics_starter','ai_analytics_plus')
      then 'ai-analytics-package'
    else p_addon_id
  end;
  perform pg_advisory_xact_lock(
    hashtextextended(
      'commercial-addon:' || p_tenant_id::text || ':' || v_lock_group,
      0
    )
  );
  select * into v_existing from public.tenant_addons
  where tenant_id=p_tenant_id and idempotency_key=p_idempotency_key limit 1;
  if found then
    if v_existing.addon_id<>p_addon_id or v_existing.quantity<>p_quantity or v_existing.state<>p_state then
      raise exception using errcode='P0001',message='commercial_addon_idempotency_conflict';
    end if;
    return next v_existing; return;
  end if;

  if p_state='active' and p_billing_interval='month' then
    update public.tenant_addons set state='scheduled_change',updated_at=now()
    where tenant_id=p_tenant_id and addon_id=p_addon_id and state='active' and billing_interval='month';
    if p_addon_id in ('ai_analytics_starter','ai_analytics_plus') then
      update public.tenant_addons set state='scheduled_change',updated_at=now()
      where tenant_id=p_tenant_id and addon_id in ('ai_analytics_starter','ai_analytics_plus')
        and addon_id<>p_addon_id and state='active';
    end if;
  end if;

  insert into public.tenant_addons (
    tenant_id,addon_id,quantity,state,catalog_version,price_minor,currency,
    billing_interval,source,idempotency_key,assigned_by_user_id,updated_at
  ) values (
    p_tenant_id,p_addon_id,p_quantity,p_state,p_catalog_version,p_price_minor,'USD',
    p_billing_interval,'admin',p_idempotency_key,p_admin_user_id,now()
  ) returning * into v_created;
  return next v_created;
end;
$$;

